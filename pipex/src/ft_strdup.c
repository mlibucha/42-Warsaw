#include "../pipex.h"

char	*ft_strdup(const char *src)
{
	int		a;
	char	*p;

	a = 0;
	p = malloc(ft_strlen(src)+1);
	if (p == NULL)
		return (NULL);
	while (src[a] != '\0')
	{
		p[a] = src[a];
		a++;
	}
	p[a] = '\0';
	return (p);
}
