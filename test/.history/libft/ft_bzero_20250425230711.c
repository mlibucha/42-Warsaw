#include "libft.h"

void	ft_bzero(void *stack, size_t len)
{
	size_t	i;
	char	*ptr;

	ptr = (char *)stack;
	i = 0;
	while (i < len)
	{
		ptr[i] = '\0';
		i++;
	}
}
